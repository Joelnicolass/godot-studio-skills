-- A deck: a card in front with a 7 x 7 drawing and another one showing behind it.
local function stack(content)
	local rows = {
		"..##########",
		"..##########",
		"..........##",
		"#########.##",
	}
	for _, line in ipairs(content) do
		rows[#rows + 1] = "#" .. line .. "#.##"
	end
	rows[#rows + 1] = "#########..."
	return rows
end

